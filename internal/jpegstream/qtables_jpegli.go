const (
	jpegliDist0       = 1.5        // where the steps stop growing linearly
	jpegliGlobalScale = 1.73966010 // kGlobalScaleYCbCr
	jpegli420Scale    = 1.22       // k420GlobalScale
)

// jpegliDeadZone is how far, in steps, an AC coefficient must be from zero
// to be kept (kZeroBiasOffsetYCbCrAC of jpegli, times 100000), for the
// luminance table and the chrominance one. Rounding would keep it from
// half a step.
var jpegliDeadZone = [2]int64{59082, 58146}

// jpegliDistance is jpegli_quality_to_distance.
func jpegliDistance(quality int) float64 {
	switch {
	case quality >= 100:
		return 0.01
	case quality >= 30:
		return 0.1 + float64(float64(100-quality)*0.09)
	}
	q := float64(quality)
	return float64(53.0/3000.0*q*q) - float64(23.0/20.0*q) + 25.0
}

// jpegliScale is DistanceToScale.
func jpegliScale(distance float64, k int) float64 {
	if distance < jpegliDist0 {
		return distance
	}
	e := jpegliExponent[k]
	return math.Max(0.5*distance, math.Pow(jpegliDist0, 1-e)*math.Pow(distance, e))
}

// jpegliQuant is the step of coefficient k (natural order) of table q at
// the given quality, limited to 1..255; yuv420 for a colour image.
func jpegliQuant(quality int, q quantIndex, k int, yuv420 bool) int {
	scale := jpegliGlobalScale
	if yuv420 {
		scale *= jpegli420Scale
	}
	scale *= jpegliScale(jpegliDistance(quality), k)
	base := &jpegliBase[0]
	if q == quantIndexChrominance {
		base = &jpegliBase[2]
		if yuv420 {
			scale *= jpegli420[k]
		}
	}
	v := int(math.Round(scale * base[k]))
	return max(1, min(v, 255))
}
