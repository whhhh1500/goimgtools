// TestNearWhite: every colour whose grey is 255 is near white, so that
// Unflatten works out the grey of no other.
func TestNearWhite(t *testing.T) {
	tb := labTables()
	n := 0
	for c := 0; c < 1<<24; c++ {
		r, g, b := uint8(c>>16), uint8(c>>8), uint8(c)
		if tb.grey(r, g, b) == 255 {
			n++
			if !nearWhite(r, g, b) {
				t.Fatalf("grey(%d, %d, %d) is 255 but the colour is not near white", r, g, b)
			}
		}
	}
	if n < 20 {
		t.Errorf("only %d colours of grey 255", n)
	}
}
